-- 002: Core source data: users, merchants, uploads and the transactions hypertable.

CREATE TABLE IF NOT EXISTS users (
    user_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona     TEXT,                    -- e.g. 'student', 'young professional' (demo label)
    income_gbp  NUMERIC(10, 2),          -- yearly income
    income_band TEXT CHECK (income_band IN ('<20k', '20-35k', '35-50k', '50-80k', '80k+')),
    age_band    TEXT,                    -- e.g. '18-24'
    job_group   TEXT,
    city        TEXT,
    source      TEXT NOT NULL DEFAULT 'synthetic' CHECK (source IN ('synthetic', 'upload', 'demo')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    -- No gender column on purpose (fairness).
);
COMMENT ON TABLE users IS 'One row per person: synthetic users, demo personas and real uploads. Deleting a user deletes all their data.';

CREATE TABLE IF NOT EXISTS merchants (
    merchant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,           -- e.g. 'Tesco'
    category    TEXT NOT NULL REFERENCES categories,
    price_tier  SMALLINT CHECK (price_tier BETWEEN 1 AND 3),   -- 1 = budget, 2 = mid, 3 = premium
    city        TEXT,
    lat         DOUBLE PRECISION,
    lon         DOUBLE PRECISION,
    UNIQUE (name, city)
);
COMMENT ON TABLE merchants IS 'UK shops and services, with a price tier so we can suggest cheaper swaps.';

CREATE TABLE IF NOT EXISTS statement_uploads (
    upload_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    filename    TEXT,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_count   INT,
    status      TEXT NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'done', 'failed'))
);
COMMENT ON TABLE statement_uploads IS 'One row per bank statement CSV a user uploads.';

-- The hypertable. Tiger splits it into 1-month chunks on ts, so date-range queries stay fast.
-- tsdb.columnstore = false: TimescaleDB 2.20+ would otherwise add a compression policy,
-- which makes bulk loads and backdated uploads harder. See 099_columnstore_optional.sql.
CREATE TABLE IF NOT EXISTS transactions (
    txn_id       BIGINT GENERATED ALWAYS AS IDENTITY,
    ts           TIMESTAMPTZ NOT NULL,
    user_id      BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    merchant_id  BIGINT REFERENCES merchants,                         -- NULL for salary and transfers
    upload_id    BIGINT REFERENCES statement_uploads ON DELETE CASCADE, -- NULL for synthetic data
    amount_gbp   NUMERIC(12, 2) NOT NULL,   -- negative = money out, positive = money in
    category     TEXT NOT NULL REFERENCES categories,
    description  TEXT,                      -- statement text, e.g. 'TESCO STORES 2345 EDINBURGH'
    is_online    BOOLEAN,
    injected     BOOLEAN NOT NULL DEFAULT false,   -- true = we added this row on purpose (ground truth)
    pattern_type TEXT CHECK (pattern_type IN ('salary', 'rent', 'subscription', 'price_rise', 'duplicate', 'bill')),
    -- A hypertable's primary key must include the partition column (ts).
    PRIMARY KEY (txn_id, ts)
) WITH (
    tsdb.hypertable,
    tsdb.partition_column = 'ts',
    tsdb.chunk_interval = '1 month',
    tsdb.columnstore = false
);
COMMENT ON TABLE transactions IS 'Hypertable: one row per bank transaction. Nothing may reference this table with a foreign key.';

CREATE INDEX IF NOT EXISTS transactions_user_ts_idx     ON transactions (user_id, ts DESC);
CREATE INDEX IF NOT EXISTS transactions_merchant_ts_idx ON transactions (merchant_id, ts DESC);
