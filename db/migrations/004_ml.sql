-- 004: ML outputs. Normal tables, rebuilt by the batch job.
-- Every row about a user is deleted automatically when that user is deleted.
-- Wipe them all with: python db/reset_derived.py --yes

CREATE TABLE IF NOT EXISTS model_runs (
    model_version TEXT PRIMARY KEY,          -- e.g. '2026-11-07T22:00_kmeans6'
    kind          TEXT NOT NULL CHECK (kind IN ('kmeans', 'knn', 'recs')),
    params        JSONB,                     -- e.g. {"k": 6}
    metrics       JSONB,                     -- e.g. {"silhouette": 0.31, "precision@5": 0.4, "baseline": 0.1}
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE model_runs IS 'One row per model training run, with its settings and scores.';

CREATE TABLE IF NOT EXISTS user_merchant_stats (
    user_id     BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    merchant_id BIGINT NOT NULL REFERENCES merchants ON DELETE CASCADE,
    visits      INT NOT NULL,
    total_gbp   NUMERIC(12, 2),
    avg_gbp     NUMERIC(12, 2),
    last_visit  TIMESTAMPTZ,
    PRIMARY KEY (user_id, merchant_id)
);
COMMENT ON TABLE user_merchant_stats IS 'KNN input: how often and how much each user spends at each merchant.';

CREATE TABLE IF NOT EXISTS user_features (
    user_id               BIGINT PRIMARY KEY REFERENCES users ON DELETE CASCADE,
    -- Share of total spending in each category (0 to 1).
    share_groceries       REAL,
    share_eating_out      REAL,
    share_coffee          REAL,
    share_transport       REAL,
    share_fuel            REAL,
    share_shopping        REAL,
    share_entertainment   REAL,
    share_subscriptions   REAL,
    share_bills_utilities REAL,
    share_rent_mortgage   REAL,
    share_health          REAL,
    share_personal_care   REAL,
    share_travel          REAL,
    share_other           REAL,
    avg_ticket_gbp        NUMERIC(12, 2),   -- average spend per transaction
    txns_per_week         REAL,
    weekend_ratio         REAL,             -- share of transactions on Sat/Sun
    online_ratio          REAL,
    savings_rate          REAL,             -- (money in - money out) / money in
    model_version         TEXT REFERENCES model_runs ON DELETE CASCADE
);
COMMENT ON TABLE user_features IS 'K-means input: one row of numbers describing each user''s spending.';

CREATE TABLE IF NOT EXISTS segments (
    segment_id            INT NOT NULL,
    model_version         TEXT NOT NULL REFERENCES model_runs ON DELETE CASCADE,
    name                  TEXT,              -- e.g. 'Takeaway lovers'
    n_users               INT,
    avg_monthly_spend_gbp NUMERIC(12, 2),
    profile_json          JSONB,             -- average spend per category, e.g. {"groceries": 210.5}
    PRIMARY KEY (segment_id, model_version)
);
COMMENT ON TABLE segments IS 'K-means clusters ("people like you"), one row per segment per model run.';

CREATE TABLE IF NOT EXISTS user_segment (
    user_id       BIGINT PRIMARY KEY REFERENCES users ON DELETE CASCADE,
    segment_id    INT NOT NULL,
    model_version TEXT NOT NULL,
    distance      REAL,                      -- distance to the segment centre
    FOREIGN KEY (segment_id, model_version) REFERENCES segments ON DELETE CASCADE
);
COMMENT ON TABLE user_segment IS 'Which segment each user belongs to.';

CREATE TABLE IF NOT EXISTS user_neighbours (
    user_id       BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    neighbour_id  BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    similarity    REAL,
    rank          SMALLINT,                  -- 1 = most similar
    model_version TEXT REFERENCES model_runs ON DELETE CASCADE,
    PRIMARY KEY (user_id, neighbour_id)
);
CREATE INDEX IF NOT EXISTS user_neighbours_user_rank_idx ON user_neighbours (user_id, rank);
COMMENT ON TABLE user_neighbours IS 'KNN output: each user''s ~20 most similar users.';

CREATE TABLE IF NOT EXISTS recommendations (
    rec_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    merchant_id          BIGINT NOT NULL REFERENCES merchants ON DELETE CASCADE,  -- the suggested shop
    replaces_merchant_id BIGINT REFERENCES merchants ON DELETE CASCADE,           -- the shop it replaces
    score                REAL,
    est_saving_gbp_year  NUMERIC(10, 2),
    reason               TEXT,   -- e.g. '6 of your 10 closest matches shop at Lidl instead of Waitrose'
    model_version        TEXT REFERENCES model_runs ON DELETE CASCADE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS recommendations_user_score_idx ON recommendations (user_id, score DESC);
COMMENT ON TABLE recommendations IS 'Money-saving suggestions shown to each user, best first.';

CREATE TABLE IF NOT EXISTS rec_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rec_id      BIGINT NOT NULL REFERENCES recommendations ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    action      TEXT NOT NULL CHECK (action IN ('accepted', 'dismissed', 'clicked')),
    ts          TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE rec_feedback IS 'What users did with each recommendation (to measure if they help).';
