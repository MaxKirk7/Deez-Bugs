-- The whole database: 2 tables + 1 Tiger continuous aggregate.
-- Safe to run again: everything uses IF NOT EXISTS.
-- Applied automatically by `uv run tiger-load` (or deez_bugs.db.create_schema()).

-- One row per person. cc_num is the user ID:
--   reference users (the 908 from the dataset) keep their card number,
--   uploaded users get an automatic number (1, 2, 3, ...).
CREATE TABLE IF NOT EXISTS users (
    cc_num     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source     TEXT NOT NULL CHECK (source IN ('reference', 'upload')),
    dob        DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Every purchase from everyone (reference users and uploads), in one place.
-- A Tiger hypertable: split into monthly chunks so per-user / date queries stay fast.
CREATE TABLE IF NOT EXISTS transactions (
    cc_num   BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    ts       TIMESTAMPTZ NOT NULL,
    merchant TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN (
        'grocery_pos', 'grocery_net', 'food_dining', 'gas_transport', 'shopping_pos', 'shopping_net',
        'home', 'kids_pets', 'entertainment', 'personal_care', 'health_fitness', 'travel',
        'misc_pos', 'misc_net')),
    amount   NUMERIC(10, 2) NOT NULL CHECK (amount > 0)     -- money spent, in the data's currency
) WITH (
    tsdb.hypertable,
    tsdb.partition_column = 'ts',
    tsdb.chunk_interval = '1 month',
    tsdb.columnstore = false
);
CREATE INDEX IF NOT EXISTS transactions_cc_num_ts_idx ON transactions (cc_num, ts DESC);

-- Tiger continuous aggregate: spend per user, per category, per day, kept up to date
-- automatically. Use it for "% of spend per category" and charts instead of summing raw rows.
CREATE MATERIALIZED VIEW IF NOT EXISTS daily_category_spend
WITH (timescaledb.continuous, timescaledb.materialized_only = false) AS
SELECT time_bucket('1 day', ts) AS day, cc_num, category,
       SUM(amount) AS spend, COUNT(*) AS txn_count
FROM transactions
GROUP BY day, cc_num, category
WITH NO DATA;

SELECT add_continuous_aggregate_policy('daily_category_spend',
    start_offset => NULL, end_offset => INTERVAL '1 hour',
    schedule_interval => INTERVAL '1 hour', if_not_exists => true);
